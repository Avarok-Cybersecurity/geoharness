// docs/geo-new-parity.md, generated from parity-data.mjs. Fails when a geo.new id is missing or listed twice, or
// when a row names a GeoHarness check or citation that does not exist.
import { mdTable } from './md.mjs';
import { GEO_NEW_IDS, OUTCOMES, PARITY } from './parity-data.mjs';
import { checkCatalog, citations } from './sources.mjs';

const code = (s) => `\`${s}\``;

function validate() {
  const checks = new Set(checkCatalog().checks.map((c) => c.id));
  const { byId } = citations();
  const seen = new Map();
  for (const [ids, , outcome, mapped, cited] of PARITY) {
    if (!OUTCOMES.includes(outcome)) throw new Error(`parity: unknown outcome ${outcome}`);
    for (const id of ids.split(', ')) {
      if (seen.has(id)) throw new Error(`parity: ${id} is listed twice`);
      seen.set(id, outcome);
    }
    for (const c of mapped) if (!checks.has(c)) throw new Error(`parity: unknown GeoHarness check ${c}`);
    for (const c of cited) if (!byId.has(c)) throw new Error(`parity: unknown citation ${c}`);
    if (['added', 'mapped'].includes(outcome) && mapped.length === 0) throw new Error(`parity: ${ids} is ${outcome} but names no check`);
  }
  const missing = GEO_NEW_IDS.filter((id) => !seen.has(id));
  const extra = [...seen.keys()].filter((id) => !GEO_NEW_IDS.includes(id));
  if (missing.length + extra.length > 0) throw new Error(`parity: missing ${missing.join(' ')}; unknown ${extra.join(' ')}`);
  return { byId, seen };
}

/** Strongest grade first, as in the README's check table. */
const grades = (ids, byId) => [...new Set(ids.map((id) => byId.get(id).grade))].sort().join(', ') || '—';

export function parityDoc() {
  const { byId, seen } = validate();
  const counts = OUTCOMES.map((o) => `${o} ${[...seen.values()].filter((v) => v === o).length}`).join(', ');
  const rows = PARITY.map(([ids, what, outcome, mapped, cited, why]) => [
    ids, what, outcome, mapped.map(code).join(', ') || '—', grades(cited, byId), cited.map(code).join(', ') || '—', why || '—',
  ]);
  return [
    '# geo.new parity',
    '',
    '<!-- Generated by `npm run docs` from scripts/docs/parity-data.mjs; edit that file, not this one. -->',
    '',
    'An independent [geo.new](https://geo.new/) audit of https://geo.avarok.net/ (2026-11-19, rules `geo-new-rules-v23`)',
    'found gaps GeoHarness\'s own audit scored as perfect (99.9). Every geo.new check is mapped here onto GeoHarness:',
    'an existing check, a check added for it, the Lighthouse 100 gate, something GeoHarness generates by construction,',
    'or the reason it is not scored. Evidence grades are those of [CITATIONS.md](../CITATIONS.md); everything below',
    'grade A/B access and indexability evidence is advisory, so it lowers the score without blocking a deploy.',
    '',
    `${GEO_NEW_IDS.length} geo.new checks: ${counts}.`,
    '',
    mdTable(['geo.new', 'What it checks', 'Outcome', 'GeoHarness', 'Grade', 'Citations', 'Why'], rows),
    '',
  ].join('\n');
}
