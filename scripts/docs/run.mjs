// npm run docs: regenerates every generated section of README.md and the site sources
// (site/src/**/*.html, site/src/_headers), and docs/geo-new-parity.md. `--check` (CI) writes nothing and fails when any differs.
// Markers: <!-- generated:NAME --> … <!-- /generated:NAME --> (README.md and HTML pages).
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { ADAPTERS } from './adapters.mjs';
import { footer, header, siteStyle } from './layout.mjs';
import { parityDoc } from './parity.mjs';
import { readmeSections, siteSections } from './sections.mjs';
import { ROOT } from './sources.mjs';

const check = process.argv.includes('--check');

const idsSource = readFileSync(join(ROOT, 'host', 'src', 'adapters', 'ids.ts'), 'utf8');
for (const [id] of ADAPTERS) if (!idsSource.includes(`'${id}'`)) throw new Error(`docs adapter ${id} is not in host/src/adapters/ids.ts`);
const idCount = (idsSource.match(/'[a-z-]+'/g) ?? []).length;
if (idCount !== ADAPTERS.length) throw new Error(`host/src/adapters/ids.ts has ${idCount} adapters, scripts/docs/adapters.mjs ${ADAPTERS.length}`);
const SITE_SRC = join(ROOT, 'site', 'src');

export function replaceSections(text, sections, file) {
  let out = text;
  const seen = new Set();
  const re = /(<!-- generated:([a-z-]+) -->\n)(?:[\s\S]*?\n)?(<!-- \/generated:\2 -->)/g;
  out = out.replace(re, (_, open, name, close) => {
    if (!(name in sections)) throw new Error(`${file}: unknown generated section "${name}"`);
    seen.add(name);
    return `${open}${sections[name]}\n${close}`;
  });
  const opened = [...text.matchAll(/<!-- generated:([a-z-]+) -->/g)].map((m) => m[1]);
  for (const name of opened) if (!seen.has(name)) throw new Error(`${file}: section "${name}" has no closing marker`);
  return out;
}

function htmlFiles(dir) {
  return readdirSync(dir, { withFileTypes: true, recursive: true })
    .filter((e) => e.isFile() && e.name.endsWith('.html'))
    .map((e) => join(e.parentPath, e.name))
    .sort();
}

function headersFile(styleHash) {
  // connect-src 'self': Lighthouse fetches /robots.txt (and llms.txt) from the page itself; 'none' fails its SEO audit.
  const csp = [
    "default-src 'none'", `style-src ${styleHash}`, "img-src 'self'", "connect-src 'self'", "base-uri 'none'", "form-action 'none'",
    "frame-ancestors 'none'", "require-trusted-types-for 'script'", 'upgrade-insecure-requests',
  ].join('; ');
  return [
    '# Generated by `npm run docs` (scripts/docs/run.mjs); edit site/theme.css or that script, not this file.',
    '/*',
    `  Content-Security-Policy: ${csp}`,
    '  Strict-Transport-Security: max-age=63072000; includeSubDomains',
    '  X-Content-Type-Options: nosniff',
    '  Referrer-Policy: strict-origin-when-cross-origin',
    '  Permissions-Policy: camera=(), microphone=(), geolocation=()',
    '  Cross-Origin-Opener-Policy: same-origin',
    '  X-Frame-Options: DENY',
    '/og.png',
    '  Cache-Control: public, max-age=86400',
    '',
  ].join('\n');
}

function plan() {
  const files = new Map();
  const readme = join(ROOT, 'README.md');
  files.set(readme, replaceSections(readFileSync(readme, 'utf8'), readmeSections(), 'README.md'));
  const style = siteStyle();
  const site = { ...siteSections(), style: style.block, header: header(), footer: footer() };
  for (const f of htmlFiles(SITE_SRC)) files.set(f, replaceSections(readFileSync(f, 'utf8'), site, relative(ROOT, f)));
  files.set(join(SITE_SRC, '_headers'), headersFile(style.hash));
  files.set(join(ROOT, 'docs', 'geo-new-parity.md'), parityDoc());
  return files;
}

const stale = [];
for (const [file, text] of plan()) {
  let current;
  try { current = readFileSync(file, 'utf8'); } catch { current = undefined; }
  if (current === text) continue;
  stale.push(relative(ROOT, file));
  if (!check) writeFileSync(file, text);
}
if (check && stale.length > 0) {
  console.error(`generated docs are stale: ${stale.join(', ')}\nrun \`npm run docs\` and commit the result.`);
  process.exit(1);
}
console.log(check ? 'generated docs are current' : `updated ${stale.length} file(s)${stale.length > 0 ? `: ${stale.join(', ')}` : ''}`);
