//! `cargo run -p xtask -- gen-types|gen-checks [--check]`
//!
//! `gen-types` writes `host/src/core/types.ts` from the Rust wire types
//! (ts-rs); `gen-checks` writes `docs/generated/checks.json` from the audit
//! catalog. With `--check`, compares instead and exits 1 when the file is
//! stale. This tool is the only workspace member that performs I/O; the
//! crates stay pure.

mod checks;

use std::path::PathBuf;
use std::process::ExitCode;

use ts_rs::{Config, TS};

use geoharness_audit::types as audit;
use geoharness_core::{config, error, rag, types};

const HEADER: &str = "// Generated by `cargo run -p xtask -- gen-types` from the Rust types in crates/.\n\
// Do not edit by hand: CI runs `cargo run -p xtask -- gen-types --check`.\n\
// The boundary is specified in docs/architecture/contract.md.\n\n\
/** Every wasm export returns this envelope as a plain object. */\n\
export type Result<T> = { ok: true; value: T } | { ok: false; errors: CoreError[] };\n";

fn decls(cfg: &Config) -> Vec<String> {
    vec![
        error::CoreError::decl(cfg),
        config::SiteConfig::decl(cfg),
        config::Site::decl(cfg),
        config::IdentityKind::decl(cfg),
        config::Identity::decl(cfg),
        config::Organization::decl(cfg),
        config::ContentSignal::decl(cfg),
        config::BotGroup::decl(cfg),
        config::BotPolicy::decl(cfg),
        config::Content::decl(cfg),
        config::Llms::decl(cfg),
        config::LlmsSection::decl(cfg),
        config::Headers::decl(cfg),
        config::Prerender::decl(cfg),
        types::SiteInput::decl(cfg),
        types::Existing::decl(cfg),
        types::PageInput::decl(cfg),
        types::SiteOutput::decl(cfg),
        types::OutFile::decl(cfg),
        types::RewriteRule::decl(cfg),
        types::PageSummary::decl(cfg),
        types::LiveCheckInput::decl(cfg),
        types::LiveRequest::decl(cfg),
        types::LiveExpect::decl(cfg),
        types::LiveObservation::decl(cfg),
        audit::AuditInput::decl(cfg),
        audit::AuditPage::decl(cfg),
        audit::LiveAuditInput::decl(cfg),
        audit::AuditReport::decl(cfg),
        audit::CategoryScore::decl(cfg),
        audit::Severity::decl(cfg),
        audit::Finding::decl(cfg),
        rag::RagInput::decl(cfg),
        rag::RouteHtml::decl(cfg),
        rag::RagOutput::decl(cfg),
        rag::SidecarEntry::decl(cfg),
        rag::Edge::decl(cfg),
        rag::EdgeEnd::decl(cfg),
        rag::Relation::decl(cfg),
    ]
}

fn render() -> String {
    let cfg = Config::new().with_large_int("never");
    let mut out = HEADER.to_owned();
    for d in decls(&cfg) {
        out.push('\n');
        out.push_str("export ");
        out.push_str(d.trim());
        out.push('\n');
    }
    out
}

fn target(rel: &str) -> PathBuf {
    PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("..").join(rel)
}

const USAGE: &str = "usage: cargo run -p xtask -- gen-types|gen-checks [--check]";

fn main() -> ExitCode {
    let args: Vec<String> = std::env::args().skip(1).collect();
    let args: Vec<&str> = args.iter().map(String::as_str).collect();
    let (task, check) = match args.as_slice() {
        [task] => (*task, false),
        [task, "--check"] => (*task, true),
        _ => {
            eprintln!("{USAGE}");
            return ExitCode::from(2);
        }
    };
    let (generated, path) = match task {
        "gen-types" => (render(), target("host/src/core/types.ts")),
        "gen-checks" => (checks::render(), target("docs/generated/checks.json")),
        _ => {
            eprintln!("{USAGE}");
            return ExitCode::from(2);
        }
    };
    if check {
        return match std::fs::read_to_string(&path) {
            Ok(current) if current == generated => ExitCode::SUCCESS,
            Ok(_) => {
                eprintln!(
                    "{} is stale: run `cargo run -p xtask -- {task}`",
                    path.display()
                );
                ExitCode::FAILURE
            }
            Err(e) => {
                eprintln!("cannot read {}: {e}", path.display());
                ExitCode::FAILURE
            }
        };
    }
    let written = path
        .parent()
        .map_or(Ok(()), std::fs::create_dir_all)
        .and_then(|()| std::fs::write(&path, generated));
    match written {
        Ok(()) => ExitCode::SUCCESS,
        Err(e) => {
            eprintln!("cannot write {}: {e}", path.display());
            ExitCode::FAILURE
        }
    }
}
