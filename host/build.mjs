// Bundles host/src/cli.ts into dist/cli.mjs (committed, like other JavaScript actions).
// `--check` rebuilds in memory and fails if the committed bundle differs (CI).
import { readFile, writeFile, mkdir } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'esbuild';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const outfile = join(root, 'dist', 'cli.mjs');
const check = process.argv.includes('--check');

const result = await build({
  entryPoints: [join(root, 'host', 'src', 'cli.ts')],
  bundle: true,
  platform: 'node',
  format: 'esm',
  target: 'node22',
  outfile,
  write: false,
  legalComments: 'none',
  banner: { js: '#!/usr/bin/env node\n// Generated by host/build.mjs from host/src — do not edit.' },
  logLevel: 'warning',
});
const [file] = result.outputFiles;
if (file === undefined) throw new Error('esbuild produced no output');

if (check) {
  const committed = await readFile(outfile, 'utf8').catch(() => '');
  if (committed !== file.text) {
    console.error('dist/cli.mjs is out of date: run `npm run bundle` and commit the result.');
    process.exit(1);
  }
  console.log('dist/cli.mjs is up to date');
} else {
  await mkdir(dirname(outfile), { recursive: true });
  await writeFile(outfile, file.text, { mode: 0o755 });
  console.log(`wrote ${outfile} (${file.text.length} bytes)`);
}
